import os
import json
import joblib
import pandas as pd
import numpy as np
from typing import Dict, Any, Tuple
from backend.schemas import LoanApplicationInput, PredictionResponse

MODEL_PATH = os.path.join(os.path.dirname(__file__), '..', 'models', 'gradient_boosting_pipeline.pkl')
METADATA_PATH = os.path.join(os.path.dirname(__file__), '..', 'models', 'model_metadata.json')

class ModelService:
    _instance = None

    def __init__(self):
        self.pipeline = None
        self.metadata = None
        self.load_model()

    @classmethod
    def get_instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def load_model(self):
        if not os.path.exists(MODEL_PATH):
            raise FileNotFoundError(f"Trained model artifact not found at {MODEL_PATH}. Please run train_model.py first.")
        if not os.path.exists(METADATA_PATH):
            raise FileNotFoundError(f"Model metadata not found at {METADATA_PATH}. Please run train_model.py first.")

        self.pipeline = joblib.load(MODEL_PATH)
        with open(METADATA_PATH, 'r') as f:
            self.metadata = json.load(f)

    def prepare_dataframe(self, input_data: LoanApplicationInput) -> pd.DataFrame:
        features = self.metadata['feature_schema']['features']
        data_dict = input_data.model_dump()
        # Guarantee DataFrame has exact columns and correct ordering
        df = pd.DataFrame([{f: data_dict[f] for f in features}])
        return df

    def predict(self, input_data: LoanApplicationInput) -> PredictionResponse:
        df = self.prepare_dataframe(input_data)
        
        # Calculate raw probabilities
        probs = self.pipeline.predict_proba(df)[0]
        rejection_prob = float(probs[0])
        approval_prob = float(probs[1])

        threshold = float(self.metadata.get('selected_threshold', 0.50))
        is_approved = bool(approval_prob >= threshold)
        predicted_status = "Approved" if is_approved else "Rejected"

        # Confidence level
        margin = abs(approval_prob - threshold)
        if margin > 0.35:
            confidence = "High"
        elif margin > 0.15:
            confidence = "Moderate"
        else:
            confidence = "Borderline / Low"

        # Financial ratio
        income = input_data.income_annum if input_data.income_annum > 0 else 1.0
        dti = round(input_data.loan_amount / income, 2)

        if is_approved:
            summary = (
                f"Application is likely to be APPROVED with an estimated likelihood of {approval_prob*100:.1f}% "
                f"(decision threshold: {threshold*100:.0f}%). "
                f"Applicant financial signals and creditworthiness meet the criteria modeled by Gradient Boosting."
            )
        else:
            summary = (
                f"Application is likely to be REJECTED with an estimated rejection likelihood of {rejection_prob*100:.1f}%. "
                f"Approval probability ({approval_prob*100:.1f}%) falls below the decision threshold ({threshold*100:.0f}%)."
            )

        disclaimer = (
            "EXPERIMENTAL DEMONSTRATION NOTICE: This prediction is generated by a Machine Learning model "
            "trained on a simulated/synthetic dataset. It is not an official banking decision, credit commitment, "
            "or financial advice. True lending decisions require human underwriter evaluation and regulatory compliance."
        )

        return PredictionResponse(
            predicted_status=predicted_status,
            is_approved=is_approved,
            approval_probability=round(approval_prob, 4),
            rejection_probability=round(rejection_prob, 4),
            decision_threshold=threshold,
            confidence_level=confidence,
            debt_to_income_ratio=dti,
            summary=summary,
            disclaimer=disclaimer
        )
